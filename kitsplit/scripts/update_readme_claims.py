"""Generate the README claims block from reports/latest.json (plan §10).

    python scripts/update_readme_claims.py          # rewrite README.md
    python scripts/update_readme_claims.py --check  # exit 1 if README is stale

Only a benchmark on the held-out REAL set (dataset path ending in `eval_real`) may
produce claims. Hand-editing the block is caught by tests/unit/test_docs.py.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
README = ROOT / "README.md"
LATEST = ROOT / "reports" / "latest.json"
BEGIN, END = "<!-- claims:begin (generated by scripts/update_readme_claims.py; do not edit) -->", "<!-- claims:end -->"
STEMS = ("kick", "snare", "toms")


def claims_block(latest: Path = LATEST) -> str:
    if not latest.is_file():
        body = ("**No quality claims.** No benchmark on the held-out real drum-bus set "
                "(`data/eval_real`, plan §4.3) exists yet, and `kitsplit-v1` has not been trained.")
        return f"{BEGIN}\n{body}\n{END}"
    r = json.loads(latest.read_text())
    if Path(r["dataset"]["path"]).name != "eval_real" or r["dataset"].get("limited"):
        raise SystemExit(f"{latest}: claims only come from a full eval_real benchmark")
    models = [m for m in ("kitsplit-v1", "b1-drumsep-mdx23c-6stem") if m in r["models"]]
    lines = [f"Held-out real set: {r['dataset']['n_tracks']} tracks, git `{r['git_sha']}`, "
             f"preset `{r['preset']['name']}`. Median SDR (dB):", "",
             "| stem | " + " | ".join(models) + " |", "|---" * (len(models) + 1) + "|"]
    for s in STEMS:
        cells = [f"{r['models'][m]['groupings']['7']['summary'][s]['sdr']['median']:.2f}" for m in models]
        lines.append(f"| {s} | " + " | ".join(cells) + " |")
    return BEGIN + "\n" + "\n".join(lines) + "\n" + END


def render(text: str, block: str) -> str:
    start, end = text.index(BEGIN), text.index(END) + len(END)
    return text[:start] + block + text[end:]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = README.read_text()
    new = render(text, claims_block())
    if args.check:
        if new != text:
            print("README claims block is stale or hand-edited; run scripts/update_readme_claims.py", file=sys.stderr)
            return 1
        return 0
    README.write_text(new)
    return 0


if __name__ == "__main__":
    sys.exit(main())
