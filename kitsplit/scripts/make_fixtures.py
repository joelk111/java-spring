"""Generate tests/fixtures/ deterministically.

Deviation from plan §9.1: the audio fixtures are NOT committed (the listed set is
~18 MB of WAV, over the 5 MB budget). They are regenerated by tests/conftest.py, and
the committed MANIFEST.sha256 pins their bytes so any non-determinism shows up as a
test failure (tests/unit/test_fixtures.py) and in `kitsplit doctor`.

    python scripts/make_fixtures.py [--write-manifest]
"""

from __future__ import annotations

import argparse
import hashlib
import sys
from pathlib import Path

import numpy as np
import soundfile as sf
import torch
import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from kitsplit.data import synth  # noqa: E402
from kitsplit.io import audio  # noqa: E402

FIXTURES = ROOT / "tests" / "fixtures"
MANIFEST = FIXTURES / "MANIFEST.sha256"
SKIP_IN_MANIFEST = {"MANIFEST.sha256", ".gitignore", "README.md"}


def _write_pcm(path: Path, x: np.ndarray, sr: int, subtype: str, fmt: str = "WAV") -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    data = np.ascontiguousarray(x.T)
    with sf.SoundFile(str(path), "w", sr, data.shape[1], subtype, format=fmt) as f:
        audio._disable_peak_chunk(f)
        f.write(data)


def make_tiny_model(dest: Path) -> None:
    from kitsplit.models.backend_torch import TinyMaskNet
    from kitsplit.models.registry import sha256_file

    dest.mkdir(parents=True, exist_ok=True)
    torch.manual_seed(0)
    model = TinyMaskNet(hidden=8)
    torch.save(model.state_dict(), dest / "tiny_mask.pt")
    cfg = {
        "arch": "tiny-mask",
        "audio": {"sample_rate": 48000, "n_fft": 512, "hop_length": 128, "window": "hann"},
        "model": {"hidden": 8},
    }
    (dest / "tiny_mask_config.yaml").write_text(yaml.safe_dump(cfg, sort_keys=True))
    digest = sha256_file(dest / "tiny_mask.pt")
    base = {
        "kind": "kitsplit", "arch": "tiny-mask", "license": "test fixture", "shippable": False,
        "description": "TEST ONLY: random-weights tiny mask net",
        "weights": {"path": "tiny_mask.pt"},
        "config": {"path": "tiny_mask_config.yaml", "sha256": sha256_file(dest / "tiny_mask_config.yaml")},
        "onnx": {"path": "tiny_mask.onnx"},
    }
    (dest / "tiny.yaml").write_text(yaml.safe_dump({**base, "name": "tiny-random", "sha256": digest}, sort_keys=True))
    tampered = {**base, "name": "tampered", "sha256": "0" * 64}
    (dest / "tampered.yaml").write_text(yaml.safe_dump(tampered, sort_keys=True))


def generate(out: Path = FIXTURES) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)

    kit = synth.render_fixture_kit(48000, 8.0, seed=0)
    synth.write_render(kit, out / "synth_kit_8s_48k.wav", out / "synth_kit_8s_48k", "24")

    k44 = synth.render_fixture_kit(44100, 2.0, seed=1, quantize_bits=None)
    _write_pcm(out / "mono_44k.wav", k44.mixture.mean(axis=0, keepdims=True), 44100, "PCM_16")

    k96 = synth.render_fixture_kit(96000, 2.0, seed=2, quantize_bits=24)
    _write_pcm(out / "stereo_96k_24bit.wav", k96.mixture, 96000, "PCM_24")

    k48 = synth.render_fixture_kit(48000, 2.0, seed=3, quantize_bits=None)
    # Plan names "stereo_48k_float.flac", but FLAC cannot store float (see C-15),
    # so the float fixture is a WAV and a 24-bit FLAC fixture is added.
    _write_pcm(out / "stereo_48k_float.wav", k48.mixture, 48000, "FLOAT")
    _write_pcm(out / "stereo_48k_24bit.flac", k48.mixture, 48000, "PCM_24", "FLAC")

    _write_pcm(out / "silence_2s.wav", np.zeros((2, 96000), np.float32), 48000, "PCM_24")
    _write_pcm(out / "dc_offset.wav", np.clip(k48.mixture + 0.2, -1, 1), 48000, "PCM_24")
    _write_pcm(out / "clipped.wav", np.clip(k48.mixture * 4.0, -1, 1), 48000, "PCM_24")
    _write_pcm(out / "empty.wav", np.zeros((2, 0), np.float32), 48000, "PCM_24")
    (out / "not_audio.txt").write_text("this is not audio\n")

    for i, name in enumerate(("track_a", "track_b")):
        r = synth.render_fixture_kit(44100, 3.0, seed=10 + i)
        synth.write_render(r, out / "type1_mini" / name / "mixture.wav", out / "type1_mini" / name, "24")

    make_tiny_model(out / "models")
    return sorted(p for p in out.rglob("*") if p.is_file() and p.name not in SKIP_IN_MANIFEST
                  and p.suffix != ".onnx")


def manifest_lines(files: list[Path], root: Path = FIXTURES) -> list[str]:
    return [f"{hashlib.sha256(p.read_bytes()).hexdigest()}  {p.relative_to(root).as_posix()}" for p in files]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--write-manifest", action="store_true")
    args = ap.parse_args()
    files = generate()
    total = sum(p.stat().st_size for p in files)
    print(f"generated {len(files)} files, {total / 1e6:.1f} MB")
    if args.write_manifest:
        MANIFEST.write_text("\n".join(manifest_lines(files)) + "\n")
        print(f"wrote {MANIFEST}")


if __name__ == "__main__":
    main()
